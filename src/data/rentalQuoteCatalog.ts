const fromQuote = (workType: RentalCatalogEntry['workType'], rows: QuoteRow[]): RentalCatalogEntry[] =>
    rows.map(([mark, itemName, spec, quantity, baseFee, dailyFee]) => ({
        materialId: `daechi-${workType}-${mark}`,
        workType,
        category: workType === 'shoring' ? '시스템동바리' : '시스템비계',
        itemName,
        spec,
        quantity,
        baseFee,
        dailyFee: dailyFee ?? 0,
        ...(dailyFee === null ? { dailyFeeMissing: true } : {}),
        active: dailyFee !== null,
        // 원본에는 단위가 없어 명세표의 기본 단위 EA를 적용한다.
        unit: 'EA',
        // 자동 생성의 수량 상한과 견적 수량은 별도 값이다.
        maxQuantity: 5000,
    }));

export const rentalQuoteCatalog: RentalCatalogEntry[] = [
    ...fromQuote('shoring', shoring),
    ...fromQuote('scaffold', scaffold),
];
