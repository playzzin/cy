const toFontAwesomeExportName = (iconName: string): string => {
    const trimmed = iconName.trim();
    if (!trimmed) return '';

    if (!trimmed.includes('-')) return trimmed;

    return trimmed
        .split('-')
        .map((part, index) => {
            if (index === 0) return part;
            return part.charAt(0).toUpperCase() + part.slice(1);
        })
        .join('');
};

// Helper: Safely resolve icon from known string keys (kebab-case or camelCase)
export const resolveIcon = (iconName: string | undefined, fallback: IconDefinition = faChartPie): IconDefinition => {
    const normalizedIconName = typeof iconName === 'string' ? iconName.trim() : '';
    if (!normalizedIconName) return fallback;

    // 1. Try iconMap (preferred for kebab-case)
    if (iconMap[normalizedIconName]) return iconMap[normalizedIconName];

    // 2. Stored menus may use either faUserTie or fa-user-tie.
    const exportName = toFontAwesomeExportName(normalizedIconName);
    return iconMap[exportName] || fallback;
};


